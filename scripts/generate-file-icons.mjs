/**
 * Generates src/components/ui/svgs/file-types.tsx from the VS Code icon set
 * (vscode-icons, MIT). Only the icons listed below are emitted, as inline
 * React SVG components, so the app has no icon dependency at runtime.
 *
 *   pnpm generate:file-icons
 */
import { writeFile } from "node:fs/promises";
import { icons } from "@iconify-json/vscode-icons";
import { getIconData, iconToSVG, replaceIDs } from "@iconify/utils";

const ICONS = {
  Pdf: "file-type-pdf2",
  Excel: "file-type-excel",
  Csv: "file-type-csv",
  Word: "file-type-word",
  Powerpoint: "file-type-powerpoint",
  Image: "file-type-image",
  Markdown: "file-type-markdown",
  Text: "file-type-text",
  Json: "file-type-json",
  Zip: "file-type-zip",
  Generic: "default-file",
};

let out = `/*
 * GENERATED by scripts/generate-file-icons.mjs. Do not edit by hand.
 * Icons from vscode-icons (https://github.com/vscode-icons/vscode-icons),
 * MIT licence, via @iconify-json/vscode-icons. The markup is static, trusted
 * build output, which is why it is injected as HTML rather than converted
 * to JSX element by element.
 */
import type { SVGProps } from "react";

`;

for (const [name, id] of Object.entries(ICONS)) {
  const data = getIconData(icons, id);
  if (!data) throw new Error(`Icon not found: ${id}`);
  const { attributes, body } = iconToSVG(data, { height: "auto" });
  // Gradient ids are prefixed per icon so two different icons never share one.
  const html = replaceIDs(body, `ft-${name.toLowerCase()}-`);
  out += `const ${name.toUpperCase()}_BODY = ${JSON.stringify(html)};

export const FileIcon${name} = (props: SVGProps<SVGSVGElement>) => (
  <svg
    {...props}
    viewBox="${attributes.viewBox}"
    xmlns="http://www.w3.org/2000/svg"
    dangerouslySetInnerHTML={{ __html: ${name.toUpperCase()}_BODY }}
  />
);

`;
}

await writeFile("src/components/ui/svgs/file-types.tsx", out);
console.log(`Wrote ${Object.keys(ICONS).length} icons to src/components/ui/svgs/file-types.tsx`);
